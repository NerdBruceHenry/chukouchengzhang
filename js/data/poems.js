/** 把全文拆成诗句（按标点断开），用于逐句展示、填空、飞花令 */
export function poemLines(p) {
  return p.text.match(/[^，。？！；、]+[，。？！；、]?/g).map((s) => s.trim()).filter(Boolean);
}

/** 朗读节奏：五言 2/3，七言 2/2/3（四言 2/2） */
export function rhythm(line) {
  const core = line.replace(/[，。？！；、]/g, '');
  const tail = line.slice(core.length);
  const cut = (pos) => pos.reduce((s, p, i) => s.slice(0, p + i) + '/' + s.slice(p + i), core);
  if (core.length === 5) return cut([2]) + tail;
  if (core.length === 7) return cut([2, 4]) + tail;
  if (core.length === 4) return cut([2]) + tail;
  return line;
}

